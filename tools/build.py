#!/usr/bin/env python3
"""Build the parent firmware for one of our modes, and our PEX modules.

  tools/build.py standalone            firmware for the standalone image
  tools/build.py companion             firmware for the companion image
  tools/build.py drivers               printer PEX modules only
  tools/build.py all                   all three

A mode's defconfig is the parent's base defconfig (named on the fragment's
"#base:" line) with the fragment's lines appended, so a later line wins.
The parent seeds .config only on the first configure, so the build directory
is wiped whenever the merged defconfig changes.
"""
import argparse, hashlib, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARENT = os.path.join(ROOT, "btgw")
MODES = ("standalone", "companion")


def merged_defconfig(mode):
    frag = os.path.join(ROOT, "configs", mode + ".fragment")
    text = open(frag).read()
    m = re.search(r"^#base:\s*(\S+)", text, re.M)
    if not m:
        sys.exit("%s: no #base: line" % frag)
    base = os.path.join(PARENT, "configs", m.group(1))
    out = "# Generated by tools/build.py from btgw/configs/%s + configs/%s.fragment\n" % (m.group(1), mode)
    out += open(base).read().rstrip("\n") + "\n\n# --- %s.fragment ---\n" % mode + text
    return out


def run(cmd, **kw):
    print("+", " ".join(cmd), flush=True)
    subprocess.check_call(cmd, **kw)


def env():
    e = dict(os.environ)
    e.setdefault("PICO_SDK_PATH", os.path.expanduser("~/.pico-sdk/sdk/2.3.0"))
    tc = os.path.expanduser("~/.pico-sdk/toolchain/15_2_Rel1")
    if "PICO_TOOLCHAIN_PATH" not in e and os.path.isdir(tc):
        e["PICO_TOOLCHAIN_PATH"] = tc
    return e


def build_firmware(mode, build_root, jobs):
    bdir = os.path.join(build_root, mode)
    cfg = merged_defconfig(mode)
    digest = hashlib.sha256(cfg.encode()).hexdigest()
    stamp = os.path.join(bdir, ".btgw_printer_defconfig.sha256")
    if os.path.isdir(bdir) and (not os.path.exists(stamp) or open(stamp).read() != digest):
        print("defconfig changed: removing", bdir)
        shutil.rmtree(bdir)
    os.makedirs(bdir, exist_ok=True)
    defc = os.path.join(bdir, "defconfig")
    with open(defc, "w") as f:
        f.write(cfg)
    if not os.path.exists(os.path.join(bdir, "build.ninja")):
        run(["cmake", "-S", PARENT, "-B", bdir, "-G", "Ninja", "-DAPP_DEFCONFIG=" + defc], env=env())
        with open(stamp, "w") as f:
            f.write(digest)
    run(["cmake", "--build", bdir] + (["-j", str(jobs)] if jobs else []), env=env())
    binf = os.path.join(bdir, "btgw.bin")
    if os.path.exists(binf):
        print("%s: btgw.bin %d bytes (slot 1048576, %d spare)" %
              (mode, os.path.getsize(binf), 1048576 - os.path.getsize(binf)))


def build_drivers(build_root, jobs):
    bdir = os.path.join(build_root, "drivers")
    if not os.path.exists(os.path.join(bdir, "build.ninja")):
        run(["cmake", "-S", os.path.join(ROOT, "drivers"), "-B", bdir, "-G", "Ninja"], env=env())
    run(["cmake", "--build", bdir] + (["-j", str(jobs)] if jobs else []), env=env())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=MODES + ("drivers", "all", "defconfig"))
    ap.add_argument("--build-dir", default=os.environ.get("BTGW_PRINTER_BUILD", os.path.join(ROOT, "build")))
    ap.add_argument("--mode", choices=MODES, help="with 'defconfig': print the merged defconfig")
    ap.add_argument("-j", type=int, default=0)
    a = ap.parse_args()
    if not os.path.exists(os.path.join(PARENT, "CMakeLists.txt")):
        sys.exit("btgw/ is empty: run git submodule update --init")
    if a.what == "defconfig":
        sys.stdout.write(merged_defconfig(a.mode or "standalone"))
        return
    if a.what in MODES or a.what == "all":
        for m in (MODES if a.what == "all" else (a.what,)):
            build_firmware(m, a.build_dir, a.j)
    if a.what in ("drivers", "all"):
        build_drivers(a.build_dir, a.j)


if __name__ == "__main__":
    main()
